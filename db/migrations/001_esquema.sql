BEGIN;

-- 0. TIPOS PROPIOS

CREATE TYPE estado_documento AS ENUM ('en_confeccion', 'terminado', 'procesado');

CREATE DOMAIN cuit_dom AS varchar(11);

-- 1. CATÁLOGOS SIN DEPENDENCIAS

CREATE TABLE localidad (
    id_localidad       integer GENERATED BY DEFAULT AS IDENTITY,
    codigo_postal      varchar(10),
    nombre             varchar(80),
    provincia          varchar(50),
    encargado_regional varchar(80),
    CONSTRAINT pk_localidad PRIMARY KEY (id_localidad)
);

CREATE TABLE cepa (
    id_cepa integer GENERATED BY DEFAULT AS IDENTITY,
    nombre  varchar(60),
    tipo    varchar(10),
    CONSTRAINT pk_cepa PRIMARY KEY (id_cepa)
);

CREATE TABLE bodega (
    cuit         cuit_dom,
    razon_social varchar(120),
    domicilio    varchar(150),
    CONSTRAINT pk_bodega PRIMARY KEY (cuit)
);

CREATE TABLE transportista (
    id_transportista integer GENERATED BY DEFAULT AS IDENTITY,
    razon_social     varchar(120),
    cuit             cuit_dom,
    email            varchar(120),
    telefono         varchar(30),
    domicilio        varchar(150),
    CONSTRAINT pk_transportista PRIMARY KEY (id_transportista)
);

CREATE TABLE maridaje (
    id_maridaje          integer GENERATED BY DEFAULT AS IDENTITY,
    nombre               varchar(60),
    temperatura_servicio numeric(4,1),
    CONSTRAINT pk_maridaje PRIMARY KEY (id_maridaje)
);

CREATE TABLE finca (
    id_finca             integer GENERATED BY DEFAULT AS IDENTITY,
    nombre               varchar(80),
    superficie_hectareas numeric(10,2),
    departamento         varchar(80),
    provincia            varchar(50),
    CONSTRAINT pk_finca PRIMARY KEY (id_finca)
);

-- 2. PRIMER NIVEL CON FK

CREATE TABLE sala (
    id_sala            integer GENERATED BY DEFAULT AS IDENTITY,
    direccion          varchar(150),
    dia_cierre_semanal smallint, 
    id_localidad       integer,
    CONSTRAINT pk_sala PRIMARY KEY (id_sala),
    CONSTRAINT fk_sala_localidad FOREIGN KEY (id_localidad)
        REFERENCES localidad (id_localidad)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

CREATE TABLE empleado (
    cuit          cuit_dom,
    nombre        varchar(120),
    fecha_ingreso date,
    salario       numeric(12,2),
    id_sala       integer,
    CONSTRAINT pk_empleado PRIMARY KEY (cuit),
    CONSTRAINT fk_empleado_sala FOREIGN KEY (id_sala)
        REFERENCES sala (id_sala)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE parcela (
    id_finca             integer,
    nro_parcela          integer,
    superficie_hectareas numeric(10,2),
    anio_plantacion      integer,
    id_cepa              integer,
    CONSTRAINT pk_parcela PRIMARY KEY (id_finca, nro_parcela),
    CONSTRAINT fk_parcela_finca FOREIGN KEY (id_finca)
        REFERENCES finca (id_finca)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_parcela_cepa FOREIGN KEY (id_cepa)
        REFERENCES cepa (id_cepa)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE vino (
    cod_vino        integer GENERATED BY DEFAULT AS IDENTITY,
    nombre_comercial varchar(120),
    tipo            varchar(12),
    anada           integer,
    presentacion_ml integer,
    graduacion      numeric(4,2),
    precio_venta    numeric(12,2),
    cuit_bodega     cuit_dom,
    CONSTRAINT pk_vino PRIMARY KEY (cod_vino),
    CONSTRAINT fk_vino_bodega FOREIGN KEY (cuit_bodega)
        REFERENCES bodega (cuit)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE cliente (
    id_cliente     integer GENERATED BY DEFAULT AS IDENTITY,
    nombre         varchar(120),
    tipo           varchar(15),
    tipo_documento varchar(10),
    nro_documento  varchar(20),
    direccion      varchar(150),
    id_localidad   integer,
    fecha_alta     date,
    descuento      numeric(5,2),
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT fk_cliente_localidad FOREIGN KEY (id_localidad)
        REFERENCES localidad (id_localidad)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE lote_uva (
    nro_lote         integer,
    id_finca         integer,
    nro_parcela      integer,
    campania         integer,
    fecha_cosecha    date,
    kilos_cosechados numeric(12,2),
    cuit_bodega      cuit_dom,
    CONSTRAINT pk_lote_uva PRIMARY KEY (nro_lote),
    CONSTRAINT fk_lote_uva_parcela FOREIGN KEY (id_finca, nro_parcela)
        REFERENCES parcela (id_finca, nro_parcela)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_lote_uva_bodega FOREIGN KEY (cuit_bodega)
        REFERENCES bodega (cuit)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


-- 3. DEPENDIENTES, SUBTIPOS Y RELACIONES N:M

CREATE TABLE composicion (
    cod_vino   integer,
    id_cepa    integer,
    porcentaje numeric(5,2),
    CONSTRAINT pk_composicion PRIMARY KEY (cod_vino, id_cepa),
    CONSTRAINT fk_composicion_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_composicion_cepa FOREIGN KEY (id_cepa)
        REFERENCES cepa (id_cepa)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE vino_maridaje (
    cod_vino    integer,
    id_maridaje integer,
    CONSTRAINT pk_vino_maridaje PRIMARY KEY (cod_vino, id_maridaje),
    CONSTRAINT fk_vino_maridaje_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_vino_maridaje_maridaje FOREIGN KEY (id_maridaje)
        REFERENCES maridaje (id_maridaje)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE socio (
    id_cliente integer,
    CONSTRAINT pk_socio PRIMARY KEY (id_cliente),
    CONSTRAINT fk_socio_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE distribuidor (
    id_cliente       integer,
    zona_cobertura   varchar(80),
    nro_habilitacion varchar(30),
    CONSTRAINT pk_distribuidor PRIMARY KEY (id_cliente),
    CONSTRAINT fk_distribuidor_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE exportador (
    id_cliente            integer,
    pais_destino_principal varchar(60),
    CONSTRAINT pk_exportador PRIMARY KEY (id_cliente),
    CONSTRAINT fk_exportador_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE permiso_exportacion (
    id_cliente        integer,
    cod_permiso       varchar(20),
    fecha_emision     date,
    fecha_vencimiento date,
    CONSTRAINT pk_permiso_exportacion PRIMARY KEY (id_cliente, cod_permiso),
    CONSTRAINT fk_permiso_exportacion_exportador FOREIGN KEY (id_cliente)
        REFERENCES exportador (id_cliente)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE transportista_localidad (
    id_transportista integer,
    id_localidad     integer,
    CONSTRAINT pk_transportista_localidad PRIMARY KEY (id_transportista, id_localidad),
    CONSTRAINT fk_transportista_localidad_transportista FOREIGN KEY (id_transportista)
        REFERENCES transportista (id_transportista)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_transportista_localidad_localidad FOREIGN KEY (id_localidad)
        REFERENCES localidad (id_localidad)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE analisis_calidad (
    id_analisis  integer GENERATED BY DEFAULT AS IDENTITY,
    nro_lote     integer,
    fecha        date,
    grado_brix   numeric(5,2),
    ph           numeric(4,2),
    acidez_total numeric(6,2), -- g/L
    CONSTRAINT pk_analisis_calidad PRIMARY KEY (id_analisis),
    CONSTRAINT fk_analisis_calidad_lote FOREIGN KEY (nro_lote)
        REFERENCES lote_uva (nro_lote)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE auditoria_precio (
    id_auditoria    integer GENERATED BY DEFAULT AS IDENTITY,
    cod_vino        integer,
    precio_anterior numeric(12,2),
    precio_nuevo    numeric(12,2),
    fecha_hora      timestamp,
    usuario         varchar(60),
    CONSTRAINT pk_auditoria_precio PRIMARY KEY (id_auditoria),
    CONSTRAINT fk_auditoria_precio_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


-- 4. MOVIMIENTOS, RENGLONES Y STOCK

CREATE TABLE comprobante (
    nro_comprobante integer GENERATED BY DEFAULT AS IDENTITY,
    fecha           date,
    id_cliente      integer,
    id_sala         integer,
    subtotal        numeric(12,2),
    descuento       numeric(12,2),
    total           numeric(12,2),
    CONSTRAINT pk_comprobante PRIMARY KEY (nro_comprobante),
    CONSTRAINT fk_comprobante_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_comprobante_sala FOREIGN KEY (id_sala)
        REFERENCES sala (id_sala)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE renglon_comprobante (
    nro_comprobante integer,
    cod_vino        integer,
    cantidad        integer,
    precio_unitario numeric(12,2),
    descuento       numeric(12,2),
    subtotal        numeric(12,2),
    CONSTRAINT pk_renglon_comprobante PRIMARY KEY (nro_comprobante, cod_vino),
    CONSTRAINT fk_renglon_comprobante_comprobante FOREIGN KEY (nro_comprobante)
        REFERENCES comprobante (nro_comprobante)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_renglon_comprobante_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE ingreso (
    cod_ingreso     integer GENERATED BY DEFAULT AS IDENTITY,
    fecha           date,
    estado          estado_documento,
    id_transportista integer,
    cuit_bodega     cuit_dom,
    CONSTRAINT pk_ingreso PRIMARY KEY (cod_ingreso),
    CONSTRAINT fk_ingreso_transportista FOREIGN KEY (id_transportista)
        REFERENCES transportista (id_transportista)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_ingreso_bodega FOREIGN KEY (cuit_bodega)
        REFERENCES bodega (cuit)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE renglon_ingreso (
    cod_ingreso integer,
    cod_vino    integer,
    cantidad    integer,
    CONSTRAINT pk_renglon_ingreso PRIMARY KEY (cod_ingreso, cod_vino),
    CONSTRAINT fk_renglon_ingreso_ingreso FOREIGN KEY (cod_ingreso)
        REFERENCES ingreso (cod_ingreso)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_renglon_ingreso_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE transferencia (
    nro_solicitud    integer GENERATED BY DEFAULT AS IDENTITY,
    id_sala          integer,
    fecha_confeccion date,
    estado           estado_documento,
    CONSTRAINT pk_transferencia PRIMARY KEY (nro_solicitud),
    CONSTRAINT fk_transferencia_sala FOREIGN KEY (id_sala)
        REFERENCES sala (id_sala)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE renglon_transferencia (
    nro_solicitud integer,
    cod_vino      integer,
    cantidad      integer,
    CONSTRAINT pk_renglon_transferencia PRIMARY KEY (nro_solicitud, cod_vino),
    CONSTRAINT fk_renglon_transferencia_transferencia FOREIGN KEY (nro_solicitud)
        REFERENCES transferencia (nro_solicitud)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_renglon_transferencia_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE stock_deposito (
    cod_vino integer,
    cantidad integer,
    CONSTRAINT pk_stock_deposito PRIMARY KEY (cod_vino),
    CONSTRAINT fk_stock_deposito_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE stock_sala (
    id_sala  integer,
    cod_vino integer,
    cantidad integer,
    CONSTRAINT pk_stock_sala PRIMARY KEY (id_sala, cod_vino),
    CONSTRAINT fk_stock_sala_sala FOREIGN KEY (id_sala)
        REFERENCES sala (id_sala)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_stock_sala_vino FOREIGN KEY (cod_vino)
        REFERENCES vino (cod_vino)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

COMMIT;
